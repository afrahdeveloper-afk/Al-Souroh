_raw_hosts = env.list('ALLOWED_HOSTS', default=['*'])
ALLOWED_HOSTS = []
CSRF_TRUSTED_ORIGINS = []

for host in _raw_hosts:
    host = host.strip().strip('/')
    if host == '*':
        ALLOWED_HOSTS.append('*')
        continue
        
    if '://' in host:
        clean_host = host.split('://')[1].split(':')[0]
        ALLOWED_HOSTS.append(clean_host)
        CSRF_TRUSTED_ORIGINS.append(host)
    else:
        clean_host = host.split(':')[0]
        ALLOWED_HOSTS.append(clean_host)
        CSRF_TRUSTED_ORIGINS.append(f"https://{clean_host}")
        CSRF_TRUSTED_ORIGINS.append(f"http://{clean_host}")
        if ':' in host:
            CSRF_TRUSTED_ORIGINS.append(f"http://{host}")

_extra_csrf = env.list('CSRF_TRUSTED_ORIGINS', default=[])
for origin in _extra_csrf:
    origin = origin.strip().rstrip('/')
    if origin and origin not in CSRF_TRUSTED_ORIGINS:
        CSRF_TRUSTED_ORIGINS.append(origin)


